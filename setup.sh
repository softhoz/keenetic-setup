read NFQWS_VARIANT
case "$NFQWS_VARIANT" in
  2)
    NFQWS_PKG="nfqws2-keenetic"
    NFQWS_REPO_NAME="nfqws2-keenetic"
    NFQWS_REPO_URL="https://nfqws.github.io/nfqws2-keenetic/all"
    NFQWS_CONF="nfqws2-keenetic.conf"
    APPLY_TEMPLATES=0
    ;;
  *)
    NFQWS_PKG="nfqws-keenetic"
    NFQWS_REPO_NAME="nfqws-keenetic"
    NFQWS_REPO_URL="https://nfqws.github.io/nfqws-keenetic/all"
    NFQWS_CONF="nfqws-keenetic.conf"
    APPLY_TEMPLATES=1
    TEMPLATE_SUBDIR="nfqws-keenetic"
    ;;
esac

# Configure NFQWS repository
log "Configuring NFQWS repository (${NFQWS_PKG})..."
mkdir -p /opt/etc/opkg || log "Failed to create opkg directory"
echo "src/gz ${NFQWS_REPO_NAME} ${NFQWS_REPO_URL}" >/opt/etc/opkg/${NFQWS_CONF} || log "Failed to add NFQWS repository"
echo "src/gz nfqws-keenetic-web https://nfqws.github.io/nfqws-keenetic-web/all" >/opt/etc/opkg/nfqws-keenetic-web.conf || log "Failed to add NFQWS-WEB repository"

# Install NFQWS
log "Updating package lists again..."
opkg update || log "Failed to update package lists"

log "Installing NFQWS..."
opkg install ${NFQWS_PKG} || log "Failed to install NFQWS"

# Install web interface (optional)
log "Installing NFQWS web interface..."
opkg install nfqws-keenetic-web || log "Failed to install NFQWS web interface"

# Apply custom config templates (stable nfqws-keenetic only)
# Templates live in this repo under templates/<subdir>/ and override the
# package defaults so manual edits in the web UI aren't needed each install.
REPO_RAW_BASE="${REPO_RAW_BASE:-https://raw.githubusercontent.com/softhoz/keenetic-setup/main}"
NFQWS_CONF_DIR="/opt/etc/nfqws"

# Copy a KEY=... line from the installed config into the fetched template so
# router-specific values set at install time (e.g. ISP_INTERFACE, which differs
# per router) survive the overwrite.
preserve_key() {
  # $1 = key, $2 = installed file (value source), $3 = template file (edited in place)
  _key="$1"; _cur="$2"; _tpl="$3"
  _line="$(grep "^${_key}=" "$_cur" 2>/dev/null | head -n1)"
  [ -z "$_line" ] && return 0
  awk -v key="$_key" -v repl="$_line" '
    !seen && $0 ~ ("^" key "=") { print repl; seen=1; next }
    { print }
  ' "$_tpl" > "${_tpl}.pres" && mv "${_tpl}.pres" "$_tpl" \
    && log "Preserved ${_key} from existing ${_name} (${_line})"
}

apply_template() {
  # $1 = filename; any further args = KEY names to preserve from the installed file
  _name="$1"; shift
  _src="${REPO_RAW_BASE}/templates/${TEMPLATE_SUBDIR}/${_name}"
  _dst="${NFQWS_CONF_DIR}/${_name}"
  _tmp="/tmp/nfqws-tmpl.${_name}.$$"
  if ! wget -q -O "$_tmp" "$_src"; then
    log "Could not fetch template ${_name}; keeping existing config"
    rm -f "$_tmp"
    return 1
  fi
  if [ ! -s "$_tmp" ]; then
    log "Template ${_name} is empty; keeping existing config"
    rm -f "$_tmp"
    return 1
  fi
  if [ -f "$_dst" ]; then
    for _key in "$@"; do
      preserve_key "$_key" "$_dst" "$_tmp"
    done
  fi
  mv "$_tmp" "$_dst" && log "Applied template ${_name}"
}

restart_nfqws() {
  _init=""
  for _f in /opt/etc/init.d/S*nfqws*; do
    if [ -x "$_f" ]; then _init="$_f"; break; fi
  done
  if [ -n "$_init" ]; then
    if "$_init" restart; then
      log "Restarted nfqws (${_init})"
    else
      log "Failed to restart nfqws"
    fi
  else
    log "nfqws init script not found; restart it manually to apply configs"
  fi
}

if [ "${APPLY_TEMPLATES:-0}" = "1" ] && [ -d "$NFQWS_CONF_DIR" ]; then
  echo ""
  echo "Custom config templates are available for ${NFQWS_PKG}."
  echo "Applying overwrites ${NFQWS_CONF_DIR}/nfqws.conf and user.list with the"
  echo "repo versions."
  printf "Apply custom config templates now? [Y/n]: "
  read APPLY_CONFIRM
  case "$APPLY_CONFIRM" in
    n|N|no|NO|No)
      log "Skipped applying config templates (user declined)"
      ;;
    *)
      log "Applying custom nfqws config templates from repo..."
      # Only ISP_INTERFACE is router-specific: it's auto-detected at install,
      # while the template ships a broad multi-WAN list. Everything else in
      # nfqws.conf (including IPV6_ENABLED) always comes from the template.
      # Let the operator choose which ISP_INTERFACE wins.
      echo ""
      echo "The template sets ISP_INTERFACE (a broad multi-WAN list); nfqws also"
      echo "auto-detects the interface for this router during installation."
      echo "  T) Use the template's ISP_INTERFACE  (broad list; good for multi-WAN/4G)"
      echo "  P) Preserve the auto-detected value  (this router's active WAN only)"
      printf "ISP_INTERFACE source? [T/p]: "
      read ISP_CHOICE
      case "$ISP_CHOICE" in
        p|P|preserve|PRESERVE)
          log "ISP_INTERFACE: preserving install-detected value"
          apply_template "nfqws.conf" "ISP_INTERFACE"
          ;;
        *)
          log "ISP_INTERFACE: using template value"
          apply_template "nfqws.conf"
          ;;
      esac
      apply_template "user.list"
      restart_nfqws
      ;;
  esac
elif [ "${APPLY_TEMPLATES:-0}" = "1" ]; then
  log "Config dir ${NFQWS_CONF_DIR} not found; skipping template application"
fi

# DNS Configuration
log "Configuring DNS servers..."
# DNS-over-TLS upstreams
ndmc -c dns-proxy tls upstream 213.202.211.221 sni ns2.opennameserver.org || log "Failed to set TLS upstream (opennameserver)"
ndmc -c dns-proxy tls upstream 77.88.8.8 sni common.dot.dns.yandex.net || log "Failed to set TLS upstream (yandex)"
ndmc -c dns-proxy tls upstream 8.8.4.4 sni dns.google || log "Failed to set TLS upstream (google)"
ndmc -c dns-proxy tls upstream 9.9.9.9 sni dns.quad9.net || log "Failed to set TLS upstream (quad9)"
ndmc -c dns-proxy tls upstream 1.1.1.1 sni cloudflare-dns.com || log "Failed to set TLS upstream (cloudflare)"
ndmc -c dns-proxy tls upstream 76.76.2.11 sni p0.freedns.controld.com || log "Failed to set TLS upstream (controld)"

# DNS-over-HTTPS upstreams (paired one-to-one with the DoT list above)
ndmc -c dns-proxy https upstream https://ns2.opennameserver.org/dns-query || log "Failed to set HTTPS upstream (opennameserver)"
ndmc -c dns-proxy https upstream https://common.dot.dns.yandex.net/dns-query || log "Failed to set HTTPS upstream (yandex)"
ndmc -c dns-proxy https upstream https://dns.google/dns-query || log "Failed to set HTTPS upstream (google)"
ndmc -c dns-proxy https upstream https://dns.quad9.net/dns-query || log "Failed to set HTTPS upstream (quad9)"
ndmc -c dns-proxy https upstream https://cloudflare-dns.com/dns-query || log "Failed to set HTTPS upstream (cloudflare)"
ndmc -c dns-proxy https upstream https://freedns.controld.com/p0 || log "Failed to set HTTPS upstream (controld)"

# Optionally ignore ISP-provided DNS so the router resolves only via the
# upstreams above. Off by default (operator opt-in).
echo ""
echo "Ignore ISP-provided DNS? The router would then resolve ONLY via the DNS"
echo "upstreams set above (enable only if those upstreams are known-good)."
printf "Ignore ISP DNS? [y/N]: "
read IGNORE_DNS_CONFIRM
case "$IGNORE_DNS_CONFIRM" in
  y|Y|yes|YES|Yes)
    # Command differs by connection type, so detect the WAN interface and try
    # the DHCP (IPoE) form first, then the PPP/IPCP form.
    log "Configuring router to ignore ISP-provided DNS..."
    WAN_IF="$(ndmc -c 'show internet status' 2>/dev/null | sed -n 's/^[[:space:]]*interface:[[:space:]]*//p' | head -n1)"
    if [ -z "$WAN_IF" ]; then
      log "Could not detect WAN interface; set 'Ignore DNS' manually in the web UI"
    else
      if ndmc -c "interface ${WAN_IF} ip dhcp client no name-servers"; then
        log "ISP IPv4 DNS ignored on ${WAN_IF} (DHCP)"
      elif ndmc -c "interface ${WAN_IF} ipcp no name-servers"; then
        log "ISP DNS ignored on ${WAN_IF} (PPP/IPCP)"
      else
        log "Could not disable ISP DNS on ${WAN_IF}; set it manually in the web UI"
      fi
      if ndmc -c "no interface ${WAN_IF} ipv6 name-servers auto"; then
        log "ISP IPv6 auto DNS ignored on ${WAN_IF}"
      else
        log "IPv6 DNS ignore skipped on ${WAN_IF} (IPv6 not configured)"
      fi
    fi
    ;;
  *)
    log "Keeping ISP-provided DNS (default)"
    ;;
esac

ndmc -c system configuration save || log "Failed to save system configuration"

log "Setup complete!"
